!>  Writes the data files for WannierTools (mtb_hr.dat, mtb_tb.dat)
!>
!>  \author       Carlos Loia Reis
!>  \version      5.13
!>  \date         2020, 23 October 2026.
!>  \copyright    GNU Public License v2

subroutine ao_interpolation_write_hr(mtb, adot, ioreplay)

! Written by Carlos Lois Reis in an unknown date.
! Documentation, indentation, ao_int_, 8 October 2024. JLM
! Constants updated to CODATA 2022 (HARTREE, EV replaced by HARTREE, BOHR). 3 October 2026. JLM+claude
! Wigner-Seitz search size question removed, nearest images of the hoppings in a single list (ndegen = 1). 23 October 2026. JLM+claude
! The MTB data is an argument (was read again from hsr.dat). 23 October 2026. JLM+claude WARNING NEW API

  use NonOrthoInterp

  implicit none

  integer, parameter           :: REAL64 = selected_real_kind(12)

  type(fiData_t)  :: ortho

! input

  integer, intent(in)                ::  ioreplay                        !<  tape number for reproducing calculations

  type(noiData_t)                    ::  mtb                             !<  see NonOrthoInterp

  real(REAL64), intent(in)           ::  adot(3,3)                       !<  metric in real space

! allocatable arrays

  complex(REAL64), allocatable ::  H(:,:),S(:,:), Hw(:,:)
  integer, allocatable         ::  irexp(:,:)                            !  lattice vectors of the nearest images
  complex(REAL64), allocatable ::  Hexp(:,:,:)                           !  orthogonalized hamiltonian for those vectors

! local variables

  real(REAL64)                 ::  avec(3,3), bvec(3,3)
  real(REAL64)                 ::  rkpt(3)

  character(len=1)             ::  yesno

  integer                      ::  nband, ikpt, jmax
  integer                      ::  nexp                                  !  number of lattice vectors of the nearest images

! counters

  integer         ::  i, j, k, n1,n2,n3

! constants

  real(REAL64), parameter     ::  BOHR = 0.5291772105_REAL64
  real(REAL64), parameter     ::  HARTREE = 27.211386246_REAL64


  nband = mtb%nband

  allocate (H(nband,nband) )
  allocate (S(nband,nband) )
  allocate (Hw(nband,nband) )

  write(6,*)
  write(6,*) '  current interpolation grid is ', mtb%fiData%mp_grid(:)
  write(6,*) '  do you want to change it (y/n) ?'
  write(6,*)

  read(5,*) yesno
  write(ioreplay,*) yesno,'   change interpolation grid'

  if(yesno == 'y' .or. yesno == 'Y') then
    write(6,*) 'enter new grid'
    read(5,*) n1,n2,n3
    write(ioreplay,'(3i5,"new grid")') n1,n2,n3
  else
    n1 = mtb%fiData%mp_grid(1)
    n2 = mtb%fiData%mp_grid(2)
    n3 = mtb%fiData%mp_grid(3)
  endif
  write(6,*) 'using ' , n1,n2,n3
  write(6,*)

  call fi_hamiltonian_setup(ortho,nband,n1,n2,n3,mtb%fiData%real_metric, &
      mtb%fiData%natsite,mtb%fiData%tau,mtb%fiData%isite)

  write(6,*) "orthogonalizing"
  write(6,*)

  ikpt = 1
  do i=1,ortho%mp_grid(1)
  do j=1,ortho%mp_grid(2)
  do k=1,ortho%mp_grid(3)

    rkpt(1) = ortho%kpt_latt(1,ikpt)
    rkpt(2) = ortho%kpt_latt(2,ikpt)
    rkpt(3) = ortho%kpt_latt(3,ikpt)

    call fi_hamiltonian_get_hk(mtb%fiData,rkpt,H, nband)
    call fi_hamiltonian_get_sk(mtb%fiData,rkpt,S, nband)

    call ao_int_OrthoH(H, S, Hw, nband)

    ortho%Ham_k(:,:,ikpt) = Hw
    ortho%S_k(:,:,ikpt) = S

!dbg    write(*,'("kpt", i5,3f8.5)') ikpt, rkpt

    call progress(ikpt,ortho%mp_grid(1)*ortho%mp_grid(2)*ortho%mp_grid(3))

    ikpt = ikpt +1

  enddo
  enddo
  enddo

  call fi_hamiltonian_get_hr(ortho)

! single list of the lattice vectors of the nearest images

  call fi_hamiltonian_expand(ortho,nband,ortho%Ham_r,nexp,irexp,Hexp)

!  write mtb_hr.dat file comptible with Wannier90

  write(6,*)
  write(6,*) "writing mtb_hr.dat and mtb_tb.dat"
  write(6,*)

  open(unit = 256 , file = "mtb_hr.dat", form="formatted")
  open(unit = 257 , file = "mtb_tb.dat", form="formatted")

  write(256,*) "generated by mtb"
  write(256,*) nband
  write(256,*) nexp

  write(257,*) "generated by mtb"
  call adot_to_avec_sym(adot,avec,bvec)

  write(257,'(3e22.12)') (avec(k,1)*BOHR,k=1,3)
  write(257,'(3e22.12)') (avec(k,2)*BOHR,k=1,3)
  write(257,'(3e22.12)') (avec(k,3)*BOHR,k=1,3)

  write(257,*) nband
  write(257,*) nexp

  do i=1, nexp, 15
    jmax = i + 14
    if(jmax > nexp) jmax = nexp
    write(256,'(15i5)') (1, j=i, jmax)
    write(257,'(15i5)') (1, j=i, jmax)
  enddo


  write(257,*)
  do i=1, nexp
        write(257,'(3i5)') irexp(:,i)
    do j=1, nband
      do k=1, nband
        write(256,'(3i5, 2i5, 2e22.12)') irexp(:,i), j, k, HARTREE*Hexp(j,k,i)
        write(257,'(2i5, 2e22.12)')                   j, k, HARTREE*Hexp(j,k,i)
      enddo
    enddo
    write(257,*)

    call progress(i,nexp)
    call flush(6)

  enddo

  close(256)
  close(257)

  deallocate(H,S,Hw)
  deallocate(irexp,Hexp)

  write(6,*)
  write(6,*) "  done "
  write(6,*)

  return

end subroutine ao_interpolation_write_hr
